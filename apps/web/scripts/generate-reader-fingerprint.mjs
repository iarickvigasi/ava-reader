// Reviewed source identity compiled into reader requests; never a qualification.
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const web = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const root = resolve(web, "../..");
const target = resolve(web, "features/reader/canonical/build.ts");
const qaConfig = resolve(web, "features/reader/qa/build-config.ts");
const qaOutput = `// Generated reader QA gate; included in the source fingerprint.\nexport const READER_QA_ENABLED = ${process.env.NEXT_PUBLIC_AVA_READER_QA === "1"};\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(qaConfig, "utf8") !== qaOutput)
    throw new Error("Stale reader QA configuration");
} else {
  mkdirSync(dirname(qaConfig), { recursive: true });
  writeFileSync(qaConfig, qaOutput);
}
// Build output contains chunk hashes, including the compiled source identity.
// Binding it would make every production build invalidate its own fingerprint.
const precacheOutput = resolve(web, "public/precache-assets.json");
const ignored = new Set([
  "node_modules",
  ".next",
  ".turbo",
  "coverage",
  "scripts",
  "dev",
  "fixtures",
]);
function files(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if (ignored.has(entry.name)) return [];
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) return files(path);
    if (
      !entry.isFile() ||
      path === target ||
      path === precacheOutput ||
      entry.name === "next-env.d.ts" ||
      /\.(test|spec)\./.test(path)
    )
      return [];
    return /\.(ts|tsx|css|json|mjs|woff2?)$/.test(path) ? [path] : [];
  });
}
const digest = (value) => createHash("sha256").update(value).digest("hex");
const entries = [
  ...files(web),
  fileURLToPath(import.meta.url),
  resolve(root, "pnpm-lock.yaml"),
]
  .map((path) => [relative(root, path), digest(readFileSync(path))])
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const fingerprint = digest(JSON.stringify(entries));
const output = `// Generated by scripts/generate-reader-fingerprint.mjs. Source identity is not qualification.\nexport const READER_BUILD_FINGERPRINT =\n  "${fingerprint}";\nexport const READER_SCHEMA = "ava-reader-3";\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output)
    throw new Error("Stale reader source fingerprint");
} else writeFileSync(target, output);
const manifestIndex = process.argv.indexOf("--manifest");
if (manifestIndex !== -1) {
  const path = process.argv[manifestIndex + 1];
  if (!path) throw new Error("A manifest output path is required");
  writeFileSync(
    path,
    JSON.stringify(
      {
        algorithm: "sha256-web-source-v1",
        fingerprint,
        qualified: false,
        files: Object.fromEntries(entries),
      },
      null,
      2,
    ) + "\n",
  );
}
process.stdout.write(fingerprint + "\n");
