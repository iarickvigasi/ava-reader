import { describe, expect, it } from "vitest";
import { splitSecondsByUtcDay } from "./split-seconds-by-utc-day";

describe("splitSecondsByUtcDay", () => {
  it.each([
    [
      "2026-04-12T23:40:00Z",
      "2026-04-13T00:30:00Z",
      [
        ["2026-04-12", 1200],
        ["2026-04-13", 1800],
      ],
    ],
    ["2026-04-12T12:00:00Z", "2026-04-12T12:10:00Z", [["2026-04-12", 600]]],
    ["2026-04-12T23:40:00Z", "2026-04-13T00:00:00Z", [["2026-04-12", 1200]]],
    ["2026-04-13T00:00:00Z", "2026-04-13T00:30:00Z", [["2026-04-13", 1800]]],
    [
      "2026-12-31T23:59:00Z",
      "2027-01-01T00:01:00Z",
      [
        ["2026-12-31", 60],
        ["2027-01-01", 60],
      ],
    ],
    [
      "2026-04-13T01:40:00+02:00",
      "2026-04-13T02:30:00+02:00",
      [
        ["2026-04-12", 1200],
        ["2026-04-13", 1800],
      ],
    ],
    [
      "2026-04-12T23:59:59.800Z",
      "2026-04-13T00:00:00.400Z",
      [["2026-04-12", 1]],
    ],
    [
      "2026-04-12T23:59:59.800Z",
      "2026-04-13T00:00:01.400Z",
      [
        ["2026-04-12", 1],
        ["2026-04-13", 1],
      ],
    ],
    [
      "2026-04-12T23:40:00Z",
      "2026-04-15T00:30:00Z",
      [
        ["2026-04-12", 1200],
        ["2026-04-13", 85200],
      ],
    ],
    ["2026-04-12T00:00:00Z", "2026-04-12T00:00:00.400Z", []],
    ["2026-04-12T00:00:00Z", "2026-04-12T00:00:00Z", []],
    ["2026-04-13T00:00:00Z", "2026-04-12T00:00:00Z", []],
    ["invalid", "2026-04-12T00:00:00Z", []],
    ["2026-04-12T00:00:00Z", "invalid", []],
  ])("splits %s → %s like server replay", (start, end, expected) => {
    expect([...splitSecondsByUtcDay(start, end)]).toEqual(expected);
  });
});
